const IDX = { en: 0, ar: 1, ku: 2 };
export const LANGS = [['ku', 'کوردی'], ['ar', 'العربية'], ['en', 'English']];
let lang = 'en';

export function detectLang(saved) {
  if (saved && IDX[saved] !== undefined) return saved;
  const n = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language]).join(',').toLowerCase()) || '';
  if (/\b(ckb|ku)/.test(n)) return 'ku';
  if (/\bar/.test(n)) return 'ar';
  return 'en';
}
export const getLang = () => lang;
export const isRTL = () => lang !== 'en';

/** Translate a key. Vars fill {placeholders}. Returns plain text. */
export function t(key, vars) {
  const row = STR[key]; let s = row ? (row[IDX[lang]] || row[0]) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}
/** Same as t() but HTML-escaped, with each var wrapped (for inline highlighting). */
export function th(key, vars = {}, wrap = (v) => v) {
  const e = (x) => String(x).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
  const row = STR[key]; const s = row ? (row[IDX[lang]] || row[0]) : key;
  return e(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? `<bdi>${wrap(e(vars[k]))}</bdi>` : m));
}

/** Switch language: sets dir/lang on <html> and fills every [data-i18n] element. */
export function setLang(l) {
  lang = IDX[l] !== undefined ? l : 'en';
  const html = document.documentElement;
  html.lang = lang === 'ku' ? 'ckb' : lang; html.dir = lang === 'en' ? 'ltr' : 'rtl';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  document.title = lang === 'en' ? 'Kurdish Tank' : t('logo') + ' · Kurdish Tank';
}

/** Translate for a specific language without touching the page (used by the trailer). */
export function tl(l, key, vars) {
  const row = STR[key]; let s = row ? (row[IDX[l] ?? 0] || row[0]) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}
